"""Portable knowledge bundles: data only, validated completely before merging.

No archive paths are extracted. Destination names are generated by EMS. Imported
instructions stay disabled until the owner reviews them in Library.
"""

import hashlib
import json
import tempfile
import uuid
import zipfile
from pathlib import Path

from app.documents.extract import SUPPORTED

MAX_BYTES = 256 * 1024**2
MAX_FILES = 500


def export_library(library, target):
    docs = library.db.documents()
    if len(docs) > MAX_FILES:
        raise ValueError("A knowledge bundle supports up to 500 files. Export a smaller library.")
    records, total = [], 0
    # Callers hold queue_lock so imports/deletes/indexing cannot change files.
    with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for doc in docs:
            path = library.path(doc["id"])
            total += path.stat().st_size
            if total > MAX_BYTES:
                raise ValueError("This library is larger than the 256 MB transfer limit. Move larger files separately.")
            name = "files/" + doc["id"] + path.suffix
            content = path.read_bytes()
            archive.writestr(name, content)
            records.append({"path": name, "name": doc["name"], "sha256": hashlib.sha256(content).hexdigest(),
                "instructions": doc["instructions"], "enabled": bool(doc["enabled"])})
        archive.writestr("manifest.json", json.dumps({"format": "ems-knowledge", "version": 1,
            "instructions": library.db.knowledge()["instructions"], "files": records}, ensure_ascii=False))


def import_library(library, source):
    """Return IDs to index; duplicates never change existing owner's decisions."""
    try:
        with zipfile.ZipFile(source) as archive, tempfile.TemporaryDirectory(dir=library.db.data, prefix="knowledge-import-") as tmp:
            infos = archive.infolist()
            if len(infos) > MAX_FILES + 1 or sum(x.file_size for x in infos) > MAX_BYTES + 2 * 1024**2:
                raise ValueError("Knowledge bundle exceeds the safe transfer limit.")
            names = [x.filename for x in infos]
            if len(set(names)) != len(names) or "manifest.json" not in names:
                raise ValueError("The bundle manifest is missing or duplicated.")
            if archive.getinfo("manifest.json").file_size > 2 * 1024**2:
                raise ValueError("The bundle manifest is too large.")
            manifest = json.loads(archive.read("manifest.json"))
            if manifest.get("format") != "ems-knowledge" or type(manifest.get("version")) is not int or manifest["version"] != 1:
                raise ValueError("This knowledge bundle needs a different EMS version.")
            records = manifest.get("files")
            instructions = manifest.get("instructions", "")
            if not isinstance(records, list) or len(records) > MAX_FILES or not isinstance(instructions, str) or len(instructions) > 2000:
                raise ValueError("Invalid knowledge bundle instructions or file list.")
            staged, seen = [], set()
            for record in records:
                if not isinstance(record, dict):
                    raise ValueError("Invalid knowledge bundle file record.")
                name, member = record.get("name"), record.get("path")
                guidance = record.get("instructions", "")
                if (not isinstance(name, str) or not name or len(name) > 255 or "/" in name or "\\" in name
                    or Path(name).suffix.lower() not in SUPPORTED or not isinstance(member, str)
                    or not member.startswith("files/") or "/" in member[6:] or "\\" in member
                    or member in seen or member not in names or not isinstance(guidance, str) or len(guidance) > 1000
                    or type(record.get("enabled", True)) is not bool):
                    raise ValueError("The knowledge bundle contains an invalid file entry.")
                seen.add(member)
                if archive.getinfo(member).file_size > library.settings.snapshot()["documents"]["max_file_mb"] * 1024**2:
                    raise ValueError("A bundled file exceeds this computer's upload limit.")
                content = archive.read(member)
                digest = hashlib.sha256(content).hexdigest()
                if digest != record.get("sha256"):
                    raise ValueError("A bundled file failed its integrity check. Export a new copy from the original computer.")
                path = Path(tmp) / (uuid.uuid4().hex + Path(name).suffix.lower())
                path.write_bytes(content)
                staged.append((path, name, digest, guidance, record.get("enabled", True)))
            if set(names) != seen | {"manifest.json"}:
                raise ValueError("Unexpected files in knowledge bundle.")
            created, duplicates, moved = [], 0, []
            # Files and metadata form one merge. Roll back moved files on failure.
            try:
                with library.db.connect() as db:
                    db.execute("BEGIN IMMEDIATE")
                    for path, name, digest, guidance, enabled in staged:
                        if db.execute("SELECT 1 FROM documents WHERE digest=?", (digest,)).fetchone():
                            duplicates += 1
                            continue
                        import time
                        doc_id = uuid.uuid4().hex
                        dest = library.folder / (doc_id + path.suffix)
                        path.replace(dest)
                        moved.append(dest)
                        db.execute("INSERT INTO documents(id,name,digest,status,created,instructions,enabled,instructions_enabled) VALUES(?,?,?,'queued',?,?,?,0)",
                            (doc_id, name, digest, time.time(), guidance, int(enabled)))
                        created.append(doc_id)
            except BaseException:
                for path in moved:
                    path.unlink(missing_ok=True)
                raise
            return {"created": created, "duplicates": duplicates, "instructions_to_review": instructions}
    except (zipfile.BadZipFile, KeyError, TypeError, AttributeError, UnicodeError, json.JSONDecodeError, RuntimeError) as exc:
        raise ValueError("This is not a valid EMS knowledge bundle. Export it again from Library.") from exc
